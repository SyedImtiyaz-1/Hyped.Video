#!/usr/bin/env python3
"""Writes runner/src/fonts.ts: the measurements reel.ts needs to fit and place big words in each "Behind you" font.

For every font: the family libass looks it up by, whether it's italic, its Windows ascent and descent (libass sizes a
font so that the two add up to the ASS font size), and per character the advance and the ink box, all in em. Kerning
is left out: it only ever narrows a word.

    python3 scripts/font-metrics.py <font file> ...

The six display fonts are in runner/fonts. Inter Black comes from the render image (Debian's fonts-inter package):
    docker run --rm --entrypoint cat <render image> /usr/share/fonts/opentype/inter/Inter-Black.otf > Inter-Black.otf
Needs fontTools (pip install fonttools).
"""
import json
import os
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.ttLib import TTFont

CHARS = "".join(chr(c) for c in range(32, 127)) + "‘’“”–—…₹€£"
OUT = os.path.join(os.path.dirname(__file__), "..", "runner", "src", "fonts.ts")


def face(path):
    font = TTFont(path)
    upm = font["head"].unitsPerEm
    os2 = font["OS/2"]
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    em = lambda v: round(v / upm, 3)
    table = {}
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if name is None:
            continue
        advance = font["hmtx"][name][0]
        pen = BoundsPen(glyphs)
        glyphs[name].draw(pen)
        x0, y0, x1, y1 = pen.bounds or (0, 0, 0, 0)
        table[ch] = [em(advance), em(x0), em(x1), em(y0), em(y1)]
    return {
        "family": font["name"].getDebugName(1),
        "italic": bool(os2.fsSelection & 1),
        "asc": em(os2.usWinAscent),
        "desc": em(os2.usWinDescent),
        "glyphs": table,
    }


def main(paths):
    faces = {}
    for path in paths:
        f = face(path)
        faces[f["family"]] = f
    lines = [
        "// Generated by scripts/font-metrics.py from the font files: don't edit by hand.",
        "// Per font: the family libass looks it up by, whether it's italic, its Windows ascent and descent (libass sizes a",
        "// font so that the two add up to the ASS font size), and per character [advance, ink left, ink right, ink bottom,",
        "// ink top], all in em, y up from the baseline.",
        "export type Face = { family: string; italic: boolean; asc: number; desc: number; glyphs: Record<string, readonly [number, number, number, number, number]> };",
        "",
        "export const FACES = {",
    ]
    for family, f in faces.items():
        glyphs = ", ".join(f"{json.dumps(ch, ensure_ascii=False)}: [{', '.join(str(v) for v in g)}]" for ch, g in f["glyphs"].items())
        lines.append(f"  {json.dumps(family)}: {{ family: {json.dumps(family)}, italic: {'true' if f['italic'] else 'false'}, asc: {f['asc']}, desc: {f['desc']}, glyphs: {{ {glyphs} }} }},")
    lines += ["} as const satisfies Record<string, Face>;", "", "export type FaceName = keyof typeof FACES;", ""]
    with open(OUT, "w") as out:
        out.write("\n".join(lines))
    print(f"{os.path.relpath(OUT)}: {', '.join(faces)}")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
